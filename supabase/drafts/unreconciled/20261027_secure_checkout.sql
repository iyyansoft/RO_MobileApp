  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id varchar(64) NOT NULL REFERENCES public.orders(order_id) ON DELETE RESTRICT,
  product_id varchar(64) NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  movement_type varchar(32) NOT NULL CHECK (movement_type IN ('order_deduction','cancellation_restock')),
  quantity integer NOT NULL CHECK (quantity > 0),
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (order_id, product_id, movement_type)
