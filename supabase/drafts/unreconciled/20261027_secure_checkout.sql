CREATE OR REPLACE FUNCTION public.ro_checkout_valid_gstin(p_gstin text)
RETURNS boolean
LANGUAGE plpgsql IMMUTABLE
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
  v_gstin text := upper(btrim(coalesce(p_gstin, '')));
  v_alphabet text := '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  v_sum integer := 0;
  v_factor integer := 2;
  v_product integer;
  v_index integer;
BEGIN
  IF v_gstin !~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$' THEN RETURN false; END IF;
  FOR v_index IN REVERSE 14..1 LOOP
    v_product := (position(substr(v_gstin, v_index, 1) IN v_alphabet) - 1) * v_factor;
    v_sum := v_sum + (v_product / 36) + (v_product % 36);
    v_factor := CASE WHEN v_factor = 2 THEN 1 ELSE 2 END;
  END LOOP;
  RETURN substr(v_gstin, 15, 1) = substr(v_alphabet, ((36 - (v_sum % 36)) % 36) + 1, 1);
END;
$$;

CREATE OR REPLACE FUNCTION public.ro_checkout_fingerprint(p_payload jsonb)
RETURNS text
LANGUAGE sql IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT md5(jsonb_build_object(
    'paymentMethod',p_payload->>'paymentMethod',
    'items',(SELECT coalesce(jsonb_agg(jsonb_build_array(q.product_id,q.quantity) ORDER BY q.product_id),'[]'::jsonb)
      FROM (SELECT trim(item->>'id') AS product_id,sum((item->>'quantity')::integer)::integer AS quantity
        FROM jsonb_array_elements(p_payload->'items') AS source(item) GROUP BY trim(item->>'id')) q),
    'withGst',coalesce((p_payload->>'withGst')::boolean,true),
    'gstin',CASE WHEN coalesce((p_payload->>'withGst')::boolean,true) THEN upper(btrim(coalesce(p_payload->>'gstin',''))) ELSE '' END,
    'companyName',btrim(coalesce(p_payload->>'companyName','')),
    'panNumber',upper(btrim(coalesce(p_payload->>'panNumber',''))),
    'deliveryNote',btrim(coalesce(p_payload->>'deliveryNote','')),
    'sameAsDelivery',coalesce((p_payload->>'sameAsDelivery')::boolean,true),
    'deliveryAddress',p_payload->'deliveryAddress',
    'billingAddress',p_payload->'billingAddress'
  )::text)
$$;

-- This privileged quote is called only from Edge Functions with the service
-- role. It derives identity, approval, price and stock from PostgreSQL.
CREATE OR REPLACE FUNCTION public.ro_checkout_quote(p_auth_user_id uuid, p_payload jsonb)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_user public.users%ROWTYPE;
  v_method text;
  v_with_gst boolean;
  v_gstin text;
  v_same boolean;
  v_delivery jsonb;
  v_billing jsonb;
  v_items jsonb;
  v_subtotal numeric(10,2) := 0;
  v_discount numeric(10,2);
  v_gst numeric(10,2);
  v_fee numeric(10,2);
  v_total numeric(10,2);
  v_item record;
  v_product public.products%ROWTYPE;
BEGIN
  IF p_auth_user_id IS NULL OR jsonb_typeof(p_payload) <> 'object' THEN RAISE EXCEPTION 'Invalid checkout request'; END IF;
  SELECT * INTO v_user FROM public.users WHERE auth_user_id = p_auth_user_id FOR SHARE;
  IF NOT FOUND OR NOT v_user.email_verified OR NOT v_user.is_approved OR v_user.status <> 'approved' THEN
    RAISE EXCEPTION 'Dealer account is not approved for checkout' USING ERRCODE='42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM auth.users au WHERE au.id=p_auth_user_id AND au.email_confirmed_at IS NOT NULL) THEN
    RAISE EXCEPTION 'Verified Supabase account required' USING ERRCODE='42501';
  END IF;
  v_method := p_payload->>'paymentMethod';
  IF v_method IS NULL OR v_method NOT IN ('Cash on Delivery','Razorpay') THEN RAISE EXCEPTION 'Unsupported payment method'; END IF;
  IF jsonb_typeof(p_payload->'items') <> 'array' OR jsonb_array_length(p_payload->'items') = 0 THEN RAISE EXCEPTION 'Add products before checkout'; END IF;
  v_delivery := p_payload->'deliveryAddress';
  v_same := coalesce((p_payload->>'sameAsDelivery')::boolean, true);
  v_billing := CASE WHEN v_same THEN v_delivery ELSE p_payload->'billingAddress' END;
  IF jsonb_typeof(v_delivery) <> 'object' OR jsonb_typeof(v_billing) <> 'object' THEN RAISE EXCEPTION 'Delivery and billing addresses are required'; END IF;
  IF coalesce(v_delivery->>'name','')='' OR coalesce(v_delivery->>'mobile','')='' OR coalesce(v_delivery->>'address','')='' OR coalesce(v_delivery->>'city','')='' OR coalesce(v_delivery->>'state','')='' OR (v_delivery->>'pincode') !~ '^[0-9]{6}$' THEN RAISE EXCEPTION 'Complete delivery address is required'; END IF;
  IF NOT v_same AND (coalesce(v_billing->>'name','')='' OR coalesce(v_billing->>'mobile','')='' OR coalesce(v_billing->>'address','')='' OR coalesce(v_billing->>'city','')='' OR coalesce(v_billing->>'state','')='' OR (v_billing->>'pincode') !~ '^[0-9]{6}$') THEN RAISE EXCEPTION 'Complete billing address is required'; END IF;
  v_with_gst := coalesce((p_payload->>'withGst')::boolean, true);
  v_gstin := CASE WHEN v_with_gst THEN upper(btrim(coalesce(p_payload->>'gstin',''))) ELSE '' END;
  IF v_with_gst AND NOT public.ro_checkout_valid_gstin(v_gstin) THEN RAISE EXCEPTION 'With GST requires a valid GST number'; END IF;

  -- Preserve existing stock semantics: lock each row and validate available
  -- quantity, but do not decrement stock until shop delivery/restocking is
  -- migrated as one coherent inventory lifecycle.
  FOR v_item IN
    SELECT trim(item->>'id') AS product_id,
           sum((item->>'quantity')::integer)::integer AS quantity
    FROM jsonb_array_elements(p_payload->'items') AS source(item)
    GROUP BY trim(item->>'id') ORDER BY trim(item->>'id')
  LOOP
    IF coalesce(v_item.product_id,'')='' OR v_item.quantity < 1 THEN RAISE EXCEPTION 'Product quantity must be a positive integer'; END IF;
    SELECT * INTO v_product FROM public.products WHERE id=v_item.product_id AND status <> 'inactive' FOR UPDATE;
    IF NOT FOUND OR v_product.price <= 0 THEN RAISE EXCEPTION 'A product is no longer available; refresh the cart'; END IF;
    IF v_product.stock_quantity IS NOT NULL AND v_item.quantity > v_product.stock_quantity THEN RAISE EXCEPTION 'Not enough stock for %', v_product.name; END IF;
    v_subtotal := v_subtotal + (v_product.price * v_item.quantity);
  END LOOP;
  v_subtotal := round(v_subtotal,2);
  v_discount := round(v_subtotal * 0.10,2);
  v_gst := CASE WHEN v_with_gst THEN round((v_subtotal-v_discount)*0.18,2) ELSE 0 END;
  v_fee := CASE WHEN v_subtotal > 5000 THEN 0 ELSE 250 END;
  v_total := round(v_subtotal-v_discount+v_gst+v_fee,2);

  SELECT jsonb_agg(jsonb_build_object(
    'id',p.id,'name',p.name,'brand',p.brand,'numericPrice',p.price,
    'quantity',q.quantity,'imgSrc',coalesce(p.img,''),'sku',p.sku
  ) ORDER BY p.id) INTO v_items
  FROM (
    SELECT trim(item->>'id') AS product_id, sum((item->>'quantity')::integer)::integer AS quantity
    FROM jsonb_array_elements(p_payload->'items') AS source(item)
    GROUP BY trim(item->>'id')
  ) q JOIN public.products p ON p.id=q.product_id;

  RETURN jsonb_build_object(
    'dealerId',v_user.id,'dealerEmail',v_user.email,'dealerName',v_user.name,
    'dealerBusiness',coalesce(v_user.business_name,''),'paymentMethod',v_method,
    'items',v_items,'withGst',v_with_gst,'gstin',v_gstin,
    'companyName',coalesce(nullif(btrim(p_payload->>'companyName'),''),v_user.business_name,''),
    'panNumber',upper(coalesce(p_payload->>'panNumber','')),
    'deliveryNote',coalesce(p_payload->>'deliveryNote',''),'sameAsDelivery',v_same,
    'deliveryAddress',v_delivery,'billingAddress',v_billing,
    'subtotal',v_subtotal,'discount',v_discount,'gst',v_gst,
    'deliveryFee',v_fee,'grandTotal',v_total
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.ro_get_checkout_session(p_auth_user_id uuid, p_request_id uuid)
RETURNS jsonb
LANGUAGE sql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT jsonb_build_object('gatewayOrderId',s.gateway_order_id,'amountPaise',s.amount_paise,
    'status',s.status,'orderId',s.order_id,'requestFingerprint',s.request_fingerprint)
  FROM public.checkout_sessions s
  WHERE s.auth_user_id=p_auth_user_id AND s.request_id=p_request_id
$$;

CREATE OR REPLACE FUNCTION public.ro_register_razorpay_checkout(
  p_auth_user_id uuid, p_request_id uuid, p_payload jsonb,
  p_gateway_order_id text, p_amount_paise bigint
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE v_quote jsonb; v_fingerprint text; v_session public.checkout_sessions%ROWTYPE;
BEGIN
  v_quote := public.ro_checkout_quote(p_auth_user_id,p_payload);
  IF coalesce(p_gateway_order_id,'')='' OR p_amount_paise <> round((v_quote->>'grandTotal')::numeric*100)::bigint THEN RAISE EXCEPTION 'Gateway order amount does not match current checkout'; END IF;
  v_fingerprint := public.ro_checkout_fingerprint(p_payload);
  INSERT INTO public.checkout_sessions(auth_user_id,request_id,dealer_id,request_fingerprint,quote,gateway_order_id,amount_paise,status)
  VALUES(p_auth_user_id,p_request_id,(v_quote->>'dealerId'),v_fingerprint,v_quote,p_gateway_order_id,p_amount_paise,'razorpay_pending')
  ON CONFLICT(auth_user_id,request_id) DO NOTHING;
  SELECT * INTO v_session FROM public.checkout_sessions WHERE auth_user_id=p_auth_user_id AND request_id=p_request_id FOR UPDATE;
  IF v_session.request_fingerprint <> v_fingerprint THEN RAISE EXCEPTION 'Checkout details changed; create a new checkout request'; END IF;
  IF v_session.gateway_order_id IS NULL THEN
    UPDATE public.checkout_sessions SET gateway_order_id=p_gateway_order_id,amount_paise=p_amount_paise,updated_at=CURRENT_TIMESTAMP
      WHERE auth_user_id=p_auth_user_id AND request_id=p_request_id RETURNING * INTO v_session;
  END IF;
  RETURN jsonb_build_object('gatewayOrderId',v_session.gateway_order_id,'amountPaise',v_session.amount_paise,'status',v_session.status,'orderId',v_session.order_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.ro_finalize_checkout(
  p_auth_user_id uuid, p_request_id uuid, p_payload jsonb,
  p_gateway_order_id text DEFAULT NULL, p_payment_id text DEFAULT NULL,
  p_shop_default_name text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_quote jsonb; v_session public.checkout_sessions%ROWTYPE; v_order_id text;
  v_invoice text; v_payment_status text; v_assignment text;
  v_item jsonb; v_points integer; v_shops text[]; v_default text; v_has_session boolean;
  v_fingerprint text; v_saved_payment_status text; v_saved_order_status text;
  v_stock integer; v_item_quantity integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(p_auth_user_id::text||p_request_id::text,0));
  v_fingerprint := public.ro_checkout_fingerprint(p_payload);
  SELECT * INTO v_session FROM public.checkout_sessions
    WHERE auth_user_id=p_auth_user_id AND request_id=p_request_id FOR UPDATE;
  v_has_session := FOUND;
  IF v_has_session AND v_session.request_fingerprint <> v_fingerprint THEN
    RAISE EXCEPTION 'Checkout details changed; create a new checkout request';
  END IF;
  IF v_has_session AND v_session.status='completed' AND v_session.order_id IS NOT NULL THEN
    SELECT payment_status,status INTO v_saved_payment_status,v_saved_order_status FROM public.orders WHERE order_id=v_session.order_id;
    IF lower(coalesce(v_saved_order_status,''))='cancelled' THEN RAISE EXCEPTION 'This checkout order was cancelled'; END IF;
    RETURN jsonb_build_object('success',true,'idempotent',true,'order',jsonb_build_object('orderId',v_session.order_id,'paymentStatus',v_saved_payment_status));
  END IF;
  IF p_payload->>'paymentMethod'='Razorpay' THEN
    IF NOT v_has_session OR v_session.gateway_order_id IS DISTINCT FROM p_gateway_order_id
       OR v_session.amount_paise <> round((v_session.quote->>'grandTotal')::numeric*100)::bigint
       OR coalesce(p_payment_id,'')='' THEN RAISE EXCEPTION 'Payment checkout was not found or does not match'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.users u JOIN auth.users au ON au.id=u.auth_user_id
      WHERE u.auth_user_id=p_auth_user_id AND au.email_confirmed_at IS NOT NULL
        AND u.email_verified=true AND u.is_approved=true AND u.status='approved') THEN
      RAISE EXCEPTION 'Dealer account is not approved for checkout' USING ERRCODE='42501';
    END IF;
    v_quote := v_session.quote;
  ELSIF p_payload->>'paymentMethod'='Cash on Delivery' AND p_gateway_order_id IS NULL AND p_payment_id IS NULL THEN
    IF v_has_session AND v_session.gateway_order_id IS NOT NULL THEN RAISE EXCEPTION 'This request already started online payment'; END IF;
    v_quote := public.ro_checkout_quote(p_auth_user_id,p_payload);
  ELSE
    RAISE EXCEPTION 'Unsupported payment confirmation';
  END IF;

  v_order_id := 'RO-'||md5(p_auth_user_id::text||':'||p_request_id::text);
  v_invoice := 'INV-'||replace(gen_random_uuid()::text,'-','');
  v_payment_status := CASE WHEN v_quote->>'paymentMethod'='Razorpay' THEN 'paid' ELSE 'due_on_delivery' END;
  INSERT INTO public.orders(order_id,user_id,user_email,user_name,user_business,subtotal,discount,gst,delivery_fee,grand_total,
    with_gst,payment_status,razorpay_payment_id,payment_method,billing_address,company_name,gstin,pan_number,same_as_delivery,
    delivery_address,delivery_note,status,invoice_number)
  VALUES(v_order_id,(v_quote->>'dealerId'),v_quote->>'dealerEmail',v_quote->>'dealerName',v_quote->>'dealerBusiness',
    (v_quote->>'subtotal')::numeric,(v_quote->>'discount')::numeric,(v_quote->>'gst')::numeric,(v_quote->>'deliveryFee')::numeric,
    (v_quote->>'grandTotal')::numeric,(v_quote->>'withGst')::boolean,v_payment_status,p_payment_id,v_quote->>'paymentMethod',
    (v_quote->'billingAddress')::text,v_quote->>'companyName',v_quote->>'gstin',v_quote->>'panNumber',
    (v_quote->>'sameAsDelivery')::boolean,(v_quote->'deliveryAddress')::text,v_quote->>'deliveryNote','Processing & Dispatched',v_invoice);
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_quote->'items') LOOP
    INSERT INTO public.order_items(order_id,product_id,product_name,brand,unit_price,quantity,img_src,sku)
    VALUES(v_order_id,v_item->>'id',v_item->>'name',v_item->>'brand',(v_item->>'numericPrice')::numeric,
      (v_item->>'quantity')::integer,v_item->>'imgSrc',v_item->>'sku');
  END LOOP;

  -- Re-check under row locks at the write boundary. The earlier quote can
  -- become stale while a Razorpay payment is being authorized. The order,
  -- stock decrement, and ledger rows commit or roll back as one transaction.
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_quote->'items') ORDER BY value->>'id' LOOP
    v_item_quantity := (v_item->>'quantity')::integer;
    SELECT stock_quantity INTO v_stock FROM public.products
      WHERE id=(v_item->>'id') AND lower(coalesce(status,'')) <> 'inactive' FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'A product is no longer available; refresh the cart'; END IF;
    IF v_stock IS NOT NULL AND v_stock < v_item_quantity THEN
      RAISE EXCEPTION 'Not enough stock for %', v_item->>'name';
    END IF;
    IF v_stock IS NOT NULL THEN
      UPDATE public.products SET stock_quantity=stock_quantity-v_item_quantity WHERE id=(v_item->>'id');
      INSERT INTO public.checkout_inventory_movements(order_id,product_id,movement_type,quantity)
        VALUES(v_order_id,v_item->>'id','order_deduction',v_item_quantity);
    END IF;
  END LOOP;
  v_points := floor((v_quote->>'grandTotal')::numeric*0.05)::integer;
  UPDATE public.users SET reward_points=reward_points+v_points WHERE id=v_quote->>'dealerId';
  INSERT INTO public.rewards_history(user_id,order_id,order_amount,points_earned)
    VALUES(v_quote->>'dealerId',v_order_id,(v_quote->>'grandTotal')::numeric,v_points);

  -- Preserve the existing shop routing rule: configured shop, otherwise the
  -- sole active shop; ambiguous multi-shop routing fails closed.
  SELECT array_agg(shop_name::text ORDER BY lower(shop_name::text)) INTO v_shops FROM (
    SELECT DISTINCT ON (lower(shop_name)) shop_name FROM public.shop_employees
    WHERE active=true AND nullif(btrim(shop_name),'') IS NOT NULL ORDER BY lower(shop_name),shop_name
  ) shops;
  v_default := nullif(btrim(p_shop_default_name),'');
  IF v_default IS NOT NULL THEN
    SELECT s.shop_name INTO v_assignment FROM unnest(coalesce(v_shops,ARRAY[]::text[])) AS s(shop_name)
      WHERE lower(s.shop_name)=lower(v_default) LIMIT 1;
    IF v_assignment IS NULL THEN RAISE EXCEPTION 'Configured default shop is not active'; END IF;
  ELSIF coalesce(array_length(v_shops,1),0)=1 THEN v_assignment:=v_shops[1];
  ELSIF coalesce(array_length(v_shops,1),0)>1 THEN RAISE EXCEPTION 'Order cannot be routed: configure a default shop or assign orders in Admin';
  END IF;
  IF v_assignment IS NOT NULL THEN
    INSERT INTO public.shop_order_assignments(order_id,shop_name,assigned_at) VALUES(v_order_id,v_assignment,CURRENT_TIMESTAMP);
  END IF;
  IF NOT v_has_session THEN
    INSERT INTO public.checkout_sessions(auth_user_id,request_id,dealer_id,request_fingerprint,quote,gateway_order_id,amount_paise,payment_id,order_id,status)
    VALUES(p_auth_user_id,p_request_id,(v_quote->>'dealerId'),v_fingerprint,v_quote,p_gateway_order_id,
      CASE WHEN p_gateway_order_id IS NULL THEN NULL ELSE round((v_quote->>'grandTotal')::numeric*100)::bigint END,
      p_payment_id,v_order_id,'completed');
  ELSE
    UPDATE public.checkout_sessions SET payment_id=p_payment_id,order_id=v_order_id,status='completed',updated_at=CURRENT_TIMESTAMP
      WHERE auth_user_id=p_auth_user_id AND request_id=p_request_id;
  END IF;
  RETURN jsonb_build_object('success',true,'order',jsonb_build_object('orderId',v_order_id,'paymentStatus',v_payment_status),
    'pointsEarned',v_points,'assignedShopName',v_assignment);
END;
$$;

-- Dealer cancellation is deliberately limited to unfulfilled COD orders.
-- Online-paid cancellation must wait for a verified Razorpay refund workflow;
-- delivered/partially supplied orders must use the shop/refund workflow.
CREATE OR REPLACE FUNCTION public.ro_cancel_checkout_order(
  p_auth_user_id uuid, p_order_id text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
DECLARE
  v_dealer_id varchar(64); v_order public.orders%ROWTYPE;
  v_movement record; v_inserted integer := 0; v_restocked boolean := false;
BEGIN
  IF p_auth_user_id IS NULL OR coalesce(btrim(p_order_id),'')='' THEN RAISE EXCEPTION 'Order cancellation request is invalid'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_auth_user_id::text||p_order_id,0));
  SELECT id INTO v_dealer_id FROM public.users WHERE auth_user_id=p_auth_user_id;
  IF v_dealer_id IS NULL THEN RAISE EXCEPTION 'Dealer account could not be verified' USING ERRCODE='42501'; END IF;
  SELECT * INTO v_order FROM public.orders WHERE order_id=p_order_id AND user_id=v_dealer_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Order was not found' USING ERRCODE='42501'; END IF;
  IF lower(coalesce(v_order.status,''))='cancelled' THEN
    SELECT EXISTS (SELECT 1 FROM public.checkout_inventory_movements WHERE order_id=p_order_id AND movement_type='cancellation_restock') INTO v_restocked;
    RETURN jsonb_build_object('success',true,'idempotent',true,'status','Cancelled','inventoryRestocked',v_restocked);
  END IF;
  IF lower(coalesce(v_order.payment_method,'')) NOT IN ('cash on delivery','cod')
     OR lower(coalesce(v_order.payment_status,'')) NOT IN ('due_on_delivery','pending') THEN
    RAISE EXCEPTION 'Online-paid or collected orders require a verified refund before cancellation';
  END IF;
  IF EXISTS (SELECT 1 FROM public.shop_delivery_items WHERE order_id=p_order_id)
     OR lower(coalesce(v_order.status,'')) NOT IN ('processing & dispatched','pending','processing') THEN
    RAISE EXCEPTION 'An order with delivery activity must be resolved through the shop delivery workflow';
  END IF;
  FOR v_movement IN
    SELECT m.product_id,m.quantity FROM public.checkout_inventory_movements m
    WHERE m.order_id=p_order_id AND m.movement_type='order_deduction'
    ORDER BY m.product_id FOR UPDATE
  LOOP
    INSERT INTO public.checkout_inventory_movements(order_id,product_id,movement_type,quantity)
      VALUES(p_order_id,v_movement.product_id,'cancellation_restock',v_movement.quantity)
      ON CONFLICT (order_id,product_id,movement_type) DO NOTHING;
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    IF v_inserted=1 THEN
      UPDATE public.products SET stock_quantity=stock_quantity+v_movement.quantity
        WHERE id=v_movement.product_id;
      v_restocked := true;
    END IF;
  END LOOP;
  UPDATE public.orders SET status='Cancelled',payment_status='cancelled' WHERE order_id=p_order_id;
  RETURN jsonb_build_object('success',true,'idempotent',false,'status','Cancelled','inventoryRestocked',v_restocked);
END;
$$;

