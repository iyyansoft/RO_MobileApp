-- Additive Shop Employee App schema for the existing Supabase PostgreSQL database.
-- Apply once with the backend stopped. This migration does not change or delete existing business rows.
BEGIN;

CREATE TABLE IF NOT EXISTS public.shop_employees (
  id uuid PRIMARY KEY,
  employee_id varchar(32) NOT NULL UNIQUE,
  shop_name varchar(191),
  full_name varchar(128) NOT NULL,
  password_hash varchar(255) NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Existing employee rows are kept intact; legacy rows may have no shop name.
ALTER TABLE public.shop_employees ADD COLUMN IF NOT EXISTS shop_name varchar(191);
CREATE INDEX IF NOT EXISTS idx_shop_employees_active ON public.shop_employees (active);

-- Orders are explicitly assigned by an administrator to a shop before an
-- employee can view or update them. This leaves the original orders table intact.
CREATE TABLE IF NOT EXISTS public.shop_order_assignments (
  order_id varchar(64) PRIMARY KEY REFERENCES public.orders(order_id) ON DELETE CASCADE,
  shop_name varchar(191) NOT NULL,
  assigned_by uuid REFERENCES public.shop_employees(id) ON DELETE SET NULL,
  assigned_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_shop_order_assignments_shop ON public.shop_order_assignments (lower(shop_name), assigned_at DESC);

CREATE TABLE IF NOT EXISTS public.shop_delivery_items (
  order_item_id bigint PRIMARY KEY REFERENCES public.order_items(id) ON DELETE CASCADE,
  order_id varchar(64) NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  delivered boolean NOT NULL DEFAULT false,
  delivery_confirmed boolean NOT NULL DEFAULT false,
  delivered_quantity integer NOT NULL DEFAULT 0 CHECK (delivered_quantity >= 0),
  undelivered_quantity integer NOT NULL DEFAULT 0 CHECK (undelivered_quantity >= 0),
  delivered_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (delivered_amount >= 0),
  refund_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
  refund_status varchar(32) NOT NULL DEFAULT 'not_required' CHECK (refund_status IN ('not_required', 'pending_admin_review', 'refunded')),
  refund_reference varchar(191),
  refund_notes text,
  recorded_by uuid REFERENCES public.shop_employees(id) ON DELETE SET NULL,
  delivered_at timestamp without time zone,
  updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Keep editable/submitted quantities separate from confirmation that the goods
-- were physically handed over. One-time backfill preserves confirmations made
-- by the earlier workflow; subsequent migration reruns never reclassify drafts.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'shop_delivery_items'
      AND column_name = 'delivery_confirmed'
  ) THEN
    ALTER TABLE public.shop_delivery_items
      ADD COLUMN delivery_confirmed boolean NOT NULL DEFAULT false;
    UPDATE public.shop_delivery_items
      SET delivery_confirmed = (delivered OR delivered_quantity > 0);
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_shop_delivery_order ON public.shop_delivery_items (order_id);
CREATE INDEX IF NOT EXISTS idx_shop_delivery_status ON public.shop_delivery_items (delivered, updated_at);
CREATE INDEX IF NOT EXISTS idx_shop_delivery_employee ON public.shop_delivery_items (recorded_by);

CREATE TABLE IF NOT EXISTS public.shop_admin_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id varchar(64) NOT NULL UNIQUE REFERENCES public.orders(order_id) ON DELETE CASCADE,
  employee_id uuid REFERENCES public.shop_employees(id) ON DELETE SET NULL,
  notification_type varchar(64) NOT NULL,
  message text NOT NULL,
  refund_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
  read_at timestamp without time zone,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_shop_notifications_created ON public.shop_admin_notifications (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_shop_notifications_employee ON public.shop_admin_notifications (employee_id);

CREATE TABLE IF NOT EXISTS public.shop_product_enquiries (
  id uuid PRIMARY KEY,
  employee_id uuid REFERENCES public.shop_employees(id) ON DELETE SET NULL,
  customer_name varchar(128) NOT NULL,
  company_name varchar(191) NOT NULL,
  contact_number varchar(32) NOT NULL,
  category varchar(128) NOT NULL,
  product_name varchar(255) NOT NULL,
  required_quantity integer NOT NULL CHECK (required_quantity > 0),
  remarks text,
  status varchar(32) NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'contacted', 'fulfilled', 'closed')),
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_shop_enquiries_status_created ON public.shop_product_enquiries (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_shop_enquiries_employee ON public.shop_product_enquiries (employee_id);

ALTER TABLE public.shop_employees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shop_delivery_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shop_order_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shop_admin_notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.shop_product_enquiries ENABLE ROW LEVEL SECURITY;
-- No browser/mobile direct policies: all employee access is enforced by the server API.

COMMIT;
